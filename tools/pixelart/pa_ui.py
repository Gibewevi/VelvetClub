def canvas(w, h):
    return np.zeros((h, w, 4), dtype=np.uint8)


def put(img, x, y, col, a=255):
    if 0 <= y < img.shape[0] and 0 <= x < img.shape[1]:
        img[y, x, :3] = col
        img[y, x, 3] = a


def frame(w, h, fill, border, top_light=None, bottom_dark=None, shadow=2, corner=1, accent=None,
          open_top=False, open_bottom=False):
    """A bordered box with cut corners and a hard, stepped drop shadow on the
    lower right (no blur). The box itself occupies (w - shadow, h - shadow)."""
    img = canvas(w, h)
    bw, bh = w - shadow, (h if open_bottom else h - shadow)
    bands = [(2, 90), (1, 170)][2 - shadow:] if shadow else []
    for s, alpha in bands:
        for y in range(s, bh + s):
            for x in range(s, bw + s):
                if (x >= bw or y >= bh) and not (open_bottom and y >= bh):
                    put(img, x, y, C["shadow"], alpha)
    for y in range(bh):
        for x in range(bw):
            cx = min(x, bw - 1 - x)
            cy = min(y, bh - 1 - y)
            upper = y < bh / 2
            flat = (open_top and upper) or (open_bottom and not upper)
            cut = 0 if flat else corner
            if cx + cy < cut:
                continue
            edge = cx == 0 or (cy == 0 and not flat) or (cut and cx + cy == cut)
            put(img, x, y, border if edge else fill)
    if top_light is not None:
        for x in range(2, bw - 2):
            put(img, x, 1, top_light)
    if bottom_dark is not None:
        for x in range(2, bw - 2):
            put(img, x, bh - 2, bottom_dark)
    if accent is not None:
        for x in range(corner + 1, bw - corner - 1):
            put(img, x, 0, accent)
        put(img, corner, 1, accent)
        put(img, bw - corner - 1, 1, accent)
    return img


def styles():
    s = {}
    s["panel"] = frame(16, 16, C["bg"], C["border"], top_light=C["hi"])
    # Windows: a title bar (pink accent line, rounded top) above a body.
    s["title"] = frame(16, 14, C["bar"], C["border"], top_light=C["bar_hi"], shadow=2, accent=C["accent"], open_bottom=True)
    body = frame(16, 16, C["bg"], C["border"], shadow=2, open_top=True)
    for x in range(1, 13):
        put(body, x, 0, C["border"])
    s["window"] = body
    s["button"] = frame(12, 12, C["btn"], C["btn_border"], top_light=(52, 48, 64), bottom_dark=(30, 27, 38), shadow=1)
    s["button_hover"] = frame(12, 12, C["hover"], C["hover_border"], top_light=(76, 60, 84), bottom_dark=(44, 34, 50), shadow=1)
    s["button_pressed"] = frame(12, 12, C["pressed"], C["accent"], top_light=(62, 40, 58), shadow=1)
    s["button_active"] = frame(12, 12, C["pressed"], C["accent"], top_light=(110, 66, 96), bottom_dark=(64, 38, 58), shadow=1)
    s["button_disabled"] = frame(12, 12, C["disabled"], C["disabled_border"], shadow=1)
    s["field"] = frame(12, 12, C["field"], C["btn_border"], top_light=(10, 9, 14), shadow=0)
    s["tooltip"] = frame(12, 12, C["bg"], C["accent"], shadow=1)
    return s


