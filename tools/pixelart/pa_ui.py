OUTLINE = hexrgb("120d1c")


def mono_icon(rows):
    img = canvas(10, 10)
    for y, line in enumerate(rows):
        for x, ch in enumerate(line):
            if ch == "1":
                put(img, x, y, C["ink"])
    return img


def emote(rows):
    h, w = len(rows), len(rows[0])
    img = canvas(w, h)
    for y, line in enumerate(rows):
        for x, ch in enumerate(line):
            if ch in EMOTE_COLORS:
                put(img, x, y, hexrgb(EMOTE_COLORS[ch]))
    out = img.copy()
    a = img[..., 3] > 0
    for y in range(h):
        for x in range(w):
            if not a[y, x] and any(0 <= y + dy < h and 0 <= x + dx < w and a[y + dy, x + dx] for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0))):
                put(out, x, y, OUTLINE)
    return out


def export():
    man = {"panels": {}, "icons": {}, "emotes": {}}
    for name, img in styles().items():
        save(img, f"ui/{name}.png")
        man["panels"][name] = f"ui/{name}.png"
    for name, rows in ICONS.items():
        assert len(rows) == 10 and all(len(r) == 10 for r in rows), name
        save(mono_icon(rows), f"ui/icon_{name}.png")
        man["icons"][name] = f"ui/icon_{name}.png"
    for name, rows in EMOTES.items():
        save(emote(rows), f"ui/emote_{name}.png")
        man["emotes"][name] = f"ui/emote_{name}.png"
    write_json("ui.json", man)
    return man


